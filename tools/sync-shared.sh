#!/usr/bin/env bash
# Copy the shared QML into every widget package and rebuild each config/main.xml
# from its own config/general.xml + shared/appearance.xml.
# Run it after editing anything in shared/ or a package's config/general.xml.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
for pkg in player monitor clock; do
  ui="$ROOT/$pkg/contents/ui"; cfg="$ROOT/$pkg/contents/config"
  [ -f "$cfg/general.xml" ] || { echo "skip $pkg (no config/general.xml yet)"; continue; }
  cp "$ROOT/shared/NeonPalette.qml" "$ROOT/shared/GlassCard.qml" "$ROOT/shared/ConfigAppearance.qml" "$ui/"
  {
    echo '<?xml version="1.0" encoding="UTF-8"?>'
    echo '<!-- generated by tools/sync-shared.sh: edit config/general.xml or shared/appearance.xml -->'
    echo '<kcfg xmlns="http://www.kde.org/standards/kcfg/1.0"'
    echo '      xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"'
    echo '      xsi:schemaLocation="http://www.kde.org/standards/kcfg/1.0 http://www.kde.org/standards/kcfg/1.0/kcfg.xsd">'
    echo '    <kcfgfile name=""/>'
    cat "$cfg/general.xml"
    cat "$ROOT/shared/appearance.xml"
    echo '</kcfg>'
  } > "$cfg/main.xml"
  echo "synced $pkg"
done
